"""Bake the original Diablo II poison-gas cloud into a single spritesheet.

`global/missiles/extra/poisongas.dcc` is the flat green cloud the game spawns
where poison bursts. Poison Explosion leaves one of these behind, so the importer
keeps every frame on one horizontal strip and records the DCC box origin.

`units/pal.dat` stores BGR triples, so the palette is converted before the
frames are painted. Reading it as RGB swaps red and blue and turns the green gas
into a muddy orange.

Usage:
    python tools/import_d2r_poison_cloud.py
    python tools/import_d2r_poison_cloud.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "effects" / "poison-cloud.png"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-poison-cloud.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

SOURCE_DCC = ("global", "missiles", "extra", "poisongas.dcc")
PALETTE_PATH = ("global", "palette", "units", "pal.dat")
# The cloud's own frames run at 25 fps in missiles.txt; the runtime plays the
# strip slower so one cast lingers as a ground hazard.
FRAME_RATE = 10


def build_sheet(source: Path) -> tuple[Image.Image, int, int, int, int, int]:
    path = source.joinpath(*SOURCE_DCC)
    animation = dcc.parse(path.read_bytes())
    if not animation["dirs"]:
        raise RuntimeError(f"{path} has no directions")
    direction = animation["dirs"][0]
    xmin, ymin, width, height = direction["box"]
    frames = direction["frames"]
    if not frames:
        raise RuntimeError(f"{path} has no frames")

    palette = [(red, green, blue) for blue, green, red in dcc.load_palette(source.joinpath(*PALETTE_PATH))]
    sheet = Image.new("RGBA", (width * len(frames), height), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        canvas.alpha_composite(
            dcc.frame_image(direction["bitmaps"][index], frame["width"], frame["height"], palette),
            (frame["xmin"] - xmin, frame["ymin"] - ymin),
        )
        sheet.alpha_composite(canvas, (index * width, 0))
    # The DCC box starts at the missile position, so its negation is where the
    # cloud is anchored inside the canvas.
    return sheet, len(frames), width, height, (-xmin, -ymin)


def write_metadata(frames: int, width: int, height: int, origin_x: int, origin_y: int) -> None:
    lines = [
        "/* Generated by tools/import_d2r_poison_cloud.py. Do not edit by hand. */",
        "",
        "export interface PoisonCloudArt {",
        "  path: string;",
        "  frames: number;",
        "  frameWidth: number;",
        "  frameHeight: number;",
        "  frameRate: number;",
        "  originX: number;",
        "  originY: number;",
        "}",
        "",
        "export const POISON_CLOUD_ART: PoisonCloudArt = {",
        '  path: "assets/d2survivors/effects/poison-cloud.png",',
        f"  frames: {frames},",
        f"  frameWidth: {width},",
        f"  frameHeight: {height},",
        f"  frameRate: {FRAME_RATE},",
        f"  originX: {origin_x},",
        f"  originY: {origin_y},",
        "};",
        "",
    ]
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)

    sheet, frames, width, height, (origin_x, origin_y) = build_sheet(args.source)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT, "PNG", optimize=True)
    write_metadata(frames, width, height, origin_x, origin_y)
    print(f"poison-cloud  {frames} frames  {sheet.width}x{sheet.height}  anchor ({origin_x}, {origin_y})")
    print(f"wrote {OUTPUT.relative_to(PROJECT_ROOT)}")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
