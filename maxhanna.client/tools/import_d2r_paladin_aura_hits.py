"""Build the paladin aura hit-effect sheets from the D2R overlay extraction.

Holy Fire, Holy Freeze and Holy Shock each use an original overlay cel for the
damage tick they deal to nearby monsters:

* ``global/overlays/auraholyfirehit.dcc``
* ``global/overlays/holyfreeze.dcc``
* ``global/overlays/holyshockhit.dcc``

The DCCs are single-direction animations laid out in unit space. The runtime
keeps the character's feet at the generated sheet's origin, so the same effect
can be stamped onto any monster hit by the aura tick.

Usage:
    python tools/import_d2r_paladin_aura_hits.py
    python tools/import_d2r_paladin_aura_hits.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "effects"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-paladin-aura-hits.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# key, source DCC, output slug, animation rate (frames/sec)
EFFECTS = (
    ("holyFire", "global/overlays/auraholyfirehit.dcc", "holy-fire-hit", 16),
    ("holyFreeze", "global/overlays/holyfreeze.dcc", "holy-freeze-hit", 16),
    ("holyShock", "global/overlays/holyshockhit.dcc", "holy-shock-hit", 20),
)


def load_frames(source: Path, relative: str) -> list[tuple[dict, bytearray]]:
    path = source / relative
    if not path.exists():
        raise FileNotFoundError(f"missing overlay {relative!r} below {source}")
    direction = dcc.parse(path.read_bytes())["dirs"][0]
    # D2's tiny 2x2 transparent frame is a timing placeholder, not art. Drop
    # those cels so the visible effect starts and ends with its real frames.
    frames = [
        (frame, bitmap)
        for frame, bitmap in zip(direction["frames"], direction["bitmaps"])
        if frame["width"] > 2 or frame["height"] > 2
    ]
    if not frames:
        raise ValueError(f"{relative}: no visible frames")
    return frames


def build_effect(
    source: Path,
    relative: str,
    slug: str,
    palette: list[tuple[int, int, int]],
) -> dict:
    frames = load_frames(source, relative)
    boxes = [frame for frame, _ in frames]
    left = min(frame["xmin"] for frame in boxes)
    right = max(frame["xmin"] + frame["width"] for frame in boxes)
    top = min(frame["ymin"] for frame in boxes)
    bottom = max(frame["ymin"] + frame["height"] for frame in boxes)
    cell_width = right - left
    cell_height = bottom - top

    sheet = Image.new("RGBA", (cell_width * len(frames), cell_height), (0, 0, 0, 0))
    for index, (frame, bitmap) in enumerate(frames):
        cel = dcc.frame_image(bitmap, frame["width"], frame["height"], palette)
        sheet.alpha_composite(cel, (
            index * cell_width + frame["xmin"] - left,
            frame["ymin"] - top,
        ))

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    output = OUTPUT_DIR / f"{slug}.png"
    sheet.save(output, optimize=True)
    print(f"{slug:16} {sheet.width:4}x{sheet.height:<4} {len(frames):2} frames, cell {cell_width}x{cell_height}")
    return {
        "path": f"assets/d2survivors/effects/{slug}.png",
        "columns": len(frames),
        "cellWidth": cell_width,
        "cellHeight": cell_height,
        # The unit-space origin (the target's feet) inside the shared crop.
        "originX": -left,
        "originY": -top,
    }


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_paladin_aura_hits.py. Do not edit by hand. */",
        "",
        "export interface D2PaladinAuraHitArt {",
        "  path: string;",
        "  columns: number;",
        "  frameRate: number;",
        "  cellWidth: number;",
        "  cellHeight: number;",
        "  /** Pixels from the left of the shared crop to the target's feet. */",
        "  originX: number;",
        "  /** Pixels from the top of the shared crop to the target's feet. */",
        "  originY: number;",
        "}",
        "",
        "export const D2_PALADIN_AURA_HIT_ART: Record<\"holyFire\" | \"holyFreeze\" | \"holyShock\", D2PaladinAuraHitArt> = {",
    ]
    for record in records:
        lines.append(
            f"  {record['key']}: {{ path: {json.dumps(record['path'])}, columns: {record['columns']}, "
            f"frameRate: {record['frameRate']}, cellWidth: {record['cellWidth']}, "
            f"cellHeight: {record['cellHeight']}, originX: {record['originX']}, originY: {record['originY']} }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def build(source: Path) -> None:
    # The units palette is stored BGR; swapping the channels preserves the
    # orange Holy Fire flash and blue Holy Freeze burst seen in game.
    palette = [(red, green, blue) for blue, green, red in
               dcc.load_palette(source / "global" / "palette" / "units" / "pal.dat")]
    records = []
    for key, relative, slug, frame_rate in EFFECTS:
        record = build_effect(source, relative, slug, palette)
        record["key"] = key
        record["frameRate"] = frame_rate
        records.append(record)
    write_metadata(records)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
