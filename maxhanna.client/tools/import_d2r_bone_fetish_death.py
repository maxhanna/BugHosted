"""Build the Bone Fetish death explosion sheets from the D2R overlay extraction.

Diablo II does not animate the Bone Fetish's body bursting.  It plays two
overlays where the corpse falls: ``bonefetishdeathbones`` throws a ring of
bones outward and ``bonefetishdeathcloud`` puffs the dust up around them, which
together are the explosion the game shows.  Both are single-direction,
110-frame-scale DCCs under ``global/overlays``.

The frames are packed into horizontal strips with every cel kept at the offset
it has relative to the monster's feet, so the runtime only has to anchor the
cell on the corpse.  Metadata with the strip geometry is generated next to it.

Run with:
    python tools/import_d2r_bone_fetish_death.py
    python tools/import_d2r_bone_fetish_death.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ASSET_ROOT = PROJECT_ROOT / "src" / "assets" / "d2survivors"
OUTPUT_DIR = ASSET_ROOT / "enemies" / "fx"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-enemy-fx.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# One square cel holds the widest frame of both overlays with its authored
# offset intact, so the whole explosion stays on one anchor.
CELL = 224
# Bump when the generated sheets change so cached art is refetched.
ASSET_VERSION = 1

# key, overlay stem, output slug, playback rate (frames a second)
OVERLAYS = (
    ("bones", "bonefetishdeathbones", "bone-fetish-death-bones", 12),
    ("cloud", "bonefetishdeathcloud", "bone-fetish-death-cloud", 10),
)


def build_overlay(source: Path, palette: list[tuple[int, int, int]], stem: str,
                  slug: str) -> tuple[Image.Image, int, int, int]:
    """Pack one overlay's frames into a strip, returning it and its anchor."""
    path = source / "global" / "overlays" / f"{stem}.dcc"
    if not path.exists():
        raise FileNotFoundError(f"missing bone fetish death overlay: {path}")
    animation = dcc.parse(path.read_bytes())
    direction = animation["dirs"][0]
    frames = direction["frames"]
    # The authoring offsets decide where the cel sits around the corpse's feet.
    left = -min(frame["xmin"] for frame in frames)
    top = -min(frame["ymin"] for frame in frames)
    right = max(frame["xmin"] + frame["width"] for frame in frames) + left
    bottom = max(frame["ymin"] + frame["height"] for frame in frames) + top
    if right > CELL or bottom > CELL:
        raise ValueError(f"{slug}: frames span {right}x{bottom}, larger than the {CELL}px cell")

    sheet = Image.new("RGBA", (len(frames) * CELL, CELL), (0, 0, 0, 0))
    for index, (frame, bitmap) in enumerate(zip(frames, direction["bitmaps"])):
        cel = dcc.frame_image(bitmap, frame["width"], frame["height"], palette)
        sheet.alpha_composite(cel, (index * CELL + left + frame["xmin"], top + frame["ymin"]))
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT_DIR / f"{slug}.png", optimize=True)
    return sheet, len(frames), left, top


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_bone_fetish_death.py. Do not edit by hand. */",
        "",
        "export interface D2EnemyEffectArt {",
        "  readonly path: string;",
        "  readonly columns: number;",
        "  readonly frameRate: number;",
        "  readonly cell: number;",
        "  /** Where the monster's feet sit inside one cell. */",
        "  readonly originX: number;",
        "  readonly originY: number;",
        "}",
        "",
        "/** The two overlays Diablo II plays where a Bone Fetish bursts. */",
        "export const BONE_FETISH_DEATH_ART: Record<\"bones\" | \"cloud\", D2EnemyEffectArt> = {",
    ]
    for record in records:
        lines.append(
            "  " + json.dumps(record["key"]) + ": { path: "
            + json.dumps(f"assets/d2survivors/enemies/fx/{record['slug']}.png?v={ASSET_VERSION}")
            + f", columns: {record['columns']}, frameRate: {record['frameRate']},"
            + f" cell: {CELL}, originX: {record['originX']}, originY: {record['originY']} }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.write_text("\n".join(lines), encoding="utf-8")
    print(f"{METADATA.relative_to(PROJECT_ROOT)}: {len(records)} overlays")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args()
    if not args.source.is_dir():
        raise SystemExit(f"D2R extraction not found: {args.source}")

    palette = [(red, green, blue) for blue, green, red in
               dcc.load_palette(args.source / "global" / "palette" / "units" / "pal.dat")]
    records = []
    for key, stem, slug, rate in OVERLAYS:
        sheet, columns, origin_x, origin_y = build_overlay(args.source, palette, stem, slug)
        records.append({
            "key": key, "slug": slug, "columns": columns, "frameRate": rate,
            "originX": origin_x, "originY": origin_y,
        })
        print(f"{slug}.png: {sheet.size}; {columns} frames at {rate} fps, "
              f"anchor {origin_x},{origin_y}")
    write_metadata(records)


if __name__ == "__main__":
    main()
