"""Builds Gheed's shop greetings from the shipped Diablo II: Resurrected files.

The D2R extract keeps an NPC's barks under ``data/local/sfx/act<N>/<npc>/`` and
their subtitle text under the same key in ``data/local/lng/strings/vo.json``.
Only keys whose file name is the string key are used, so every quote here is
exactly the line Gheed says in the recording. Each bark is re-encoded to the
client's small mono Ogg/Opus format (``d2r_voice_encode.py``) and written into
the client assets, and ``d2-gheed-voice.ts`` carries the matching text.
"""

import json
import os
import re
from pathlib import Path

from d2r_voice_encode import ENCODED_SUFFIX, build_take, drop_stale_flacs

EXTRACT = os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "d2", "d2r extract", "data", "local")
EXTRACT = os.path.abspath(EXTRACT)
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SOURCE_DIR = os.path.join(EXTRACT, "sfx", "act1", "gheed")
VOICE_DIR = os.path.join(REPO, "src", "assets", "d2survivors", "audio", "voice", "gheed")
OUT_FILE = os.path.join(REPO, "src", "app", "d2survivors", "d2-gheed-voice.ts")

# The short barks Gheed opens a trade with. Each file name is also its string
# key, so the subtitle cannot drift from the recording.
KEYS = [
    "ghe_greetings",
    "ghe_letsdeal",
    "ghe_mayihelpyou",
    "ghe_goodmorning",
    "ghe_goodday",
    "ghe_goodevening",
]


def clean(text):
    """Drops the leading volume code D2R prefixes some strings with."""
    text = re.sub(r"^\d+(?=\D)", "", text or "")
    text = text.replace("\r", " ").replace("\n", " ")
    return re.sub(r"\s+", " ", text).strip()


def main():
    with open(os.path.join(EXTRACT, "lng", "strings", "vo.json"), encoding="utf-8-sig") as handle:
        strings = {entry["Key"]: entry.get("enUS", "") for entry in json.load(handle)}

    os.makedirs(VOICE_DIR, exist_ok=True)
    lines = []
    for key in KEYS:
        text = clean(strings.get(key, ""))
        source = os.path.join(SOURCE_DIR, key + ".flac")
        if not text:
            raise SystemExit("missing subtitle text for " + key)
        if not os.path.isfile(source):
            raise SystemExit("missing voice file " + source)
        build_take(Path(source), Path(VOICE_DIR) / (key + ENCODED_SUFFIX))
        lines.append((key, text))

    body = "\n".join(
        '  { path: %s, text: %s },'
        % (json.dumps("assets/d2survivors/audio/voice/gheed/%s%s" % (key, ENCODED_SUFFIX)), json.dumps(text, ensure_ascii=False))
        for key, text in lines
    )

    source = """/*!
 * Gheed's spoken greetings, lifted from the shipped Diablo II: Resurrected
 * files: the audio from data/local/sfx/act1/gheed and the subtitle text from
 * the same key in that build's string table, so each quote matches the voice.
 *
 * Generated by tools/build_gheed_voice.py; add lines there rather than by hand.
 */

export interface GheedVoiceLine {
  /** Path of the voice file, relative to the client root. */
  path: string;
  /** Subtitle text shown while the line plays. */
  text: string;
}

export const GHEED_VOICE_LINES: GheedVoiceLine[] = [
%s
];

/** A greeting for the shop's opening, chosen at random. */
export function randomGheedVoiceLine(random: () => number = Math.random): GheedVoiceLine | undefined {
  if (!GHEED_VOICE_LINES.length) return undefined;
  const index = Math.min(
    GHEED_VOICE_LINES.length - 1,
    Math.floor(Math.max(0, Math.min(0.999999, random())) * GHEED_VOICE_LINES.length),
  );
  return GHEED_VOICE_LINES[index];
}
""" % body
    source = source.replace("/*!", "/**", 1)

    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(source)

    removed = drop_stale_flacs(Path(VOICE_DIR))
    if removed:
        print("removed", removed, "lossless leftover(s)")
    print("encoded", len(lines), "files")
    for key, text in lines:
        print("  ", key, "->", text)


if __name__ == "__main__":
    main()
