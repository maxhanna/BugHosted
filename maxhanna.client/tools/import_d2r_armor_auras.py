"""Build the sorceress armor aura sheets from the D2R overlay extraction.

Diablo II draws Frozen Armor, Shiver Armor and Chilling Armor with the same
`global/overlays/frozenarmor.dcc` sparkle overlay, while the extra extraction
also ships a name-matched `extra/shiversoverlay.dcc` ring. This importer bakes
one sheet per spell so each has its own art:

* Frozen Armor  - `frozenarmor.dcc`, the icy sparkles unchanged
* Shiver Armor  - `extra/shiversoverlay.dcc`, the blue shiver ring
* Chilling Armor - `frozenarmor.dcc` graded toward a pale ice-white

`units/pal.dat` stores BGR triples, so the palette is converted before the
frames are painted; reading it as RGB swaps red and blue and gives the cold
overlays a red cast.

Every frame is composited onto one 128px cell with the character's feet at
(64, 112), which is where the runtime anchors the aura. Long animations wrap to
a second row so no sheet crosses the 4096px texture limit.

Usage:
    python tools/import_d2r_armor_auras.py
    python tools/import_d2r_armor_auras.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "auras" / "armor"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-armor-auras.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

CELL = 128
ORIGIN = (64, 112)
# Keep every row under the 4096px texture limit; 33-frame Shiver Armor wraps.
MAX_COLUMNS = 30
FRAME_RATE = 16

# skill, output slug, overlay path relative to `global/overlays`, tint.
AURAS = (
    ("Frozen Armor", "frozen-armor", "frozenarmor.dcc", None),
    ("Shiver Armor", "shiver-armor", "extra/shiversoverlay.dcc", None),
    ("Chilling Armor", "chilling-armor", "frozenarmor.dcc", "frost"),
)


def frost_tint(image: Image.Image) -> Image.Image:
    """Grade the Frozen Armor sparkles toward pale ice-white for Chilling Armor."""
    pixels = image.load()
    for y in range(image.height):
        for x in range(image.width):
            red, green, blue, alpha = pixels[x, y]
            if alpha == 0:
                continue
            pixels[x, y] = (
                min(255, round(red * 0.55 + 205 * 0.45)),
                min(255, round(green * 0.6 + 236 * 0.4)),
                min(255, round(blue * 0.7 + 255 * 0.3)),
                alpha,
            )
    return image


def build_sheet(source: Path, palette: list[tuple[int, int, int]], overlay: str,
                slug: str, tint: str | None) -> tuple[Image.Image, int, int]:
    path = source / "global" / "overlays" / overlay
    animation = dcc.parse(path.read_bytes())
    direction = animation["dirs"][0]
    frames = direction["frames"]
    columns = min(len(frames), MAX_COLUMNS)
    rows = (len(frames) + columns - 1) // columns
    sheet = Image.new("RGBA", (columns * CELL, rows * CELL), (0, 0, 0, 0))

    for index, (frame, bitmap) in enumerate(zip(frames, direction["bitmaps"])):
        cel = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
        cel.alpha_composite(
            dcc.frame_image(bitmap, frame["width"], frame["height"], palette),
            (ORIGIN[0] + frame["xmin"], ORIGIN[1] + frame["ymin"]),
        )
        if tint == "frost":
            cel = frost_tint(cel)
        column = index % columns
        row = index // columns
        sheet.alpha_composite(cel, (column * CELL, row * CELL))

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT_DIR / f"{slug}.png", optimize=True)
    return sheet, columns, rows


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_armor_auras.py. Do not edit by hand. */",
        "",
        "export interface ArmorAuraArt {",
        "  path: string;",
        "  columns: number;",
        "  rows: number;",
        "  frameRate: number;",
        "  cell: number;",
        "  originX: number;",
        "  originY: number;",
        "  scale: number;",
        "}",
        "",
        "export const ARMOR_AURA_ART: Record<string, ArmorAuraArt> = {",
    ]
    for record in sorted(records, key=lambda entry: entry["skill"]):
        lines.append(
            "  "
            + json.dumps(record["skill"])
            + ": { path: "
            + json.dumps(record["path"])
            + f", columns: {record['columns']}, rows: {record['rows']}, frameRate: {record['frameRate']}"
            + f", cell: {CELL}, originX: {ORIGIN[0]}, originY: {ORIGIN[1]}, scale: 1.0 }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def build(source: Path) -> None:
    palette = [(red, green, blue) for blue, green, red in
               dcc.load_palette(source / "global" / "palette" / "units" / "pal.dat")]
    records = []
    for skill, slug, overlay, tint in AURAS:
        sheet, columns, rows = build_sheet(source, palette, overlay, slug, tint)
        records.append({
            "skill": skill,
            "path": f"assets/d2survivors/auras/armor/{slug}.png",
            "columns": columns,
            "rows": rows,
            "frameRate": FRAME_RATE,
        })
        print(f"{slug:16} {sheet.width:4}x{sheet.height:<4} {columns:2} columns x {rows} row(s)")
    write_metadata(records)
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
