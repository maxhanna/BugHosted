"""Import the interface sound Diablo II plays when gold changes hands.

``global/excel/base/sounds.txt`` names every recording the game can play;
``item_gold`` resolves to ``item/gold.flac``, the coins heard on a pickup, a
purchase and a sale. Selling gear in this client plays that same take, so this
tool decodes it and re-encodes it to mono 48 kHz Ogg/Opus (PyAV carries the
ffmpeg libraries, so no ffmpeg binary is needed) and writes the tiny table the
component reads.

Run with:
    python tools/import_d2r_ui_sounds.py
    python tools/import_d2r_ui_sounds.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import av
from av.audio.resampler import AudioResampler

PROJECT_ROOT = Path(__file__).resolve().parents[1]
AUDIO_ROOT = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "audio" / "ui"
GENERATED = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-ui-sounds.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# sounds.txt entry -> the file this client ships it as.
GOLD_SOUND = "item_gold"
GOLD_FILE = "item-gold.ogg"

ENCODED_SAMPLE_RATE = 48_000
ENCODED_BIT_RATE = 40_000

HEADER = """// Generated by tools/import_d2r_ui_sounds.py. Do not edit by hand.
// sounds.txt's item_gold: the coins Diablo II rattles whenever gold changes
// hands. The shop plays this one take on every sale.

/** The recorded coin take played when the hero sells something. */
export const ITEM_GOLD_SOUNDS: readonly string[] = [
"""

FOOTER = """];

/**
 * One coin take for a sale, or undefined when the table is somehow empty so a
 * sale can never throw over its own sound.
 */
export function randomGoldSound(random: () => number = Math.random): string | undefined {
  if (!ITEM_GOLD_SOUNDS.length) return undefined;
  const index = Math.min(ITEM_GOLD_SOUNDS.length - 1, Math.floor(Math.max(0, Math.min(0.999999, random())) * ITEM_GOLD_SOUNDS.length));
  return ITEM_GOLD_SOUNDS[index];
}
"""


def sound_files(source: Path) -> dict[str, str]:
    """sounds.txt's entry names mapped to their recording, relative to sfx."""
    table = source / "global" / "excel" / "base" / "sounds.txt"
    lines = table.read_text(encoding="utf-8", errors="replace").splitlines()
    header = lines[0].split("\t")
    sound = header.index("Sound")
    file_name = header.index("FileName")
    sounds: dict[str, str] = {}
    for line in lines[1:]:
        cells = line.split("\t")
        if len(cells) <= max(sound, file_name):
            continue
        name = cells[sound].strip()
        recording = cells[file_name].strip()
        if name and recording:
            sounds[name] = recording.replace("\\", "/")
    return sounds


def encode_take(origin: Path, target: Path) -> None:
    """Re-encode one recording to mono 48 kHz Ogg/Opus."""
    target.parent.mkdir(parents=True, exist_ok=True)
    with av.open(str(origin)) as recording:
        stream = recording.streams.audio[0]
        resampler = AudioResampler(format="fltp", layout="mono", rate=ENCODED_SAMPLE_RATE)
        with av.open(str(target), "w", format="ogg") as output:
            encoded = output.add_stream("libopus", rate=ENCODED_SAMPLE_RATE)
            encoded.layout = "mono"
            encoded.bit_rate = ENCODED_BIT_RATE
            for frame in recording.decode(stream):
                for resampled in resampler.resample(frame):
                    for packet in encoded.encode(resampled):
                        output.mux(packet)
            for packet in encoded.encode(None):
                output.mux(packet)


def build(source: Path) -> None:
    sounds = sound_files(source)
    recording = sounds.get(GOLD_SOUND)
    if not recording:
        raise FileNotFoundError(f"sounds.txt has no {GOLD_SOUND} entry")
    origin = source / "global" / "sfx" / recording
    if not origin.exists():
        raise FileNotFoundError(f"missing recording for {GOLD_SOUND}: {origin}")

    target = AUDIO_ROOT / GOLD_FILE
    if not target.exists() or target.stat().st_mtime < origin.stat().st_mtime:
        encode_take(origin, target)
    print(f"{GOLD_SOUND:12} -> {target.relative_to(PROJECT_ROOT)} ({target.stat().st_size / 1024:.1f} KiB)")

    path = f"assets/d2survivors/audio/ui/{GOLD_FILE}"
    GENERATED.write_text(
        HEADER + f'  "{path}",\n' + FOOTER,
        encoding="utf-8",
    )
    print(f"wrote {GENERATED.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    build(parser.parse_args(argv).source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
