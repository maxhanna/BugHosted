"""Bake the Diablo II Thunder Storm aura into a looping spritesheet.

`global/overlays/thunderstormcast_operate.dcc` is the 19-frame overlay that
`global/excel/overlay.txt` attaches as `thunderstormback`: the electric ring
that stays under the sorceress for the duration of Thunder Storm. The one-shot
`thunderstormcast.dcc` is only the cast flourish, not the persistent aura.

The overlay is a single direction centred on the caster's feet. Frames are
composited onto a 160px cell with the DCC origin at (80, 96), so the runtime can
anchor the whole cell to the caster's ground point while keeping the authored
frame offsets.

`units/pal.dat` stores BGR triples, so the palette is converted before the
frames are painted; reading it as RGB swaps red and blue and turns the blue
lightning purple.

Usage:
    python tools/import_d2r_thunderstorm.py
    python tools/import_d2r_thunderstorm.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "auras" / "thunderstorm.png"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-thunderstorm.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

SOURCE_DCC = ("global", "overlays", "thunderstormcast_operate.dcc")
PALETTE_PATH = ("global", "palette", "units", "pal.dat")
CELL = 160
ORIGIN = (80, 96)
FRAME_RATE = 16
SCALE = 1.4


def build_sheet(source: Path) -> tuple[Image.Image, int, int]:
    path = source.joinpath(*SOURCE_DCC)
    animation = dcc.parse(path.read_bytes())
    if not animation["dirs"]:
        raise RuntimeError(f"{path} has no directions")
    direction = animation["dirs"][0]
    frames = direction["frames"]
    if not frames:
        raise RuntimeError(f"{path} has no frames")

    palette = [(red, green, blue) for blue, green, red in dcc.load_palette(source.joinpath(*PALETTE_PATH))]
    columns = min(len(frames), 19)
    rows = (len(frames) + columns - 1) // columns
    sheet = Image.new("RGBA", (columns * CELL, rows * CELL), (0, 0, 0, 0))
    for index, (frame, bitmap) in enumerate(zip(frames, direction["bitmaps"])):
        cel = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
        cel.alpha_composite(
            dcc.frame_image(bitmap, frame["width"], frame["height"], palette),
            (ORIGIN[0] + frame["xmin"], ORIGIN[1] + frame["ymin"]),
        )
        sheet.alpha_composite(cel, ((index % columns) * CELL, (index // columns) * CELL))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT, "PNG", optimize=True)
    return sheet, columns, rows


def write_metadata(columns: int, rows: int) -> None:
    lines = [
        "/* Generated by tools/import_d2r_thunderstorm.py. Do not edit by hand. */",
        "",
        "export interface ThunderStormArt {",
        "  path: string;",
        "  columns: number;",
        "  rows: number;",
        "  frameRate: number;",
        "  cell: number;",
        "  originX: number;",
        "  originY: number;",
        "  scale: number;",
        "}",
        "",
        "export const THUNDER_STORM_ART: ThunderStormArt = {",
        '  path: "assets/d2survivors/auras/thunderstorm.png",',
        f"  columns: {columns},",
        f"  rows: {rows},",
        f"  frameRate: {FRAME_RATE},",
        f"  cell: {CELL},",
        f"  originX: {ORIGIN[0]},",
        f"  originY: {ORIGIN[1]},",
        f"  scale: {SCALE},",
        "};",
        "",
    ]
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)

    sheet, columns, rows = build_sheet(args.source)
    write_metadata(columns, rows)
    print(f"thunderstorm aura  {columns * rows} frames  {sheet.width}x{sheet.height}  anchor {ORIGIN}")
    print(f"wrote {OUTPUT.relative_to(PROJECT_ROOT)}")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
