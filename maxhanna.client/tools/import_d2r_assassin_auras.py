"""Build the Blade Sentinel aura sheet from the D2R overlay extraction.

Blade Sentinel is the Assassin's orbiting blade aura. The D2 overlay table
maps ``bladeshield`` to ``Expansion\\blade_shield.dcc``, a 20-frame spinning
ring of bright blades. The similarly named ``bladeshield back`` and
``bladeshield front`` DCCs are dark shadow passes, so compositing those gives
an almost invisible black sheet.

This importer exports the actual bright ring as a single-row sheet. The source
frames are composited at their unit-space offsets with the character's feet at
(64, 80), then downscaled to a 128px cell. The runtime draws the strip over the
assassin at the same 1.25 scale used by the paladin aura sheets.

Usage:
    python tools/import_d2r_assassin_auras.py
    python tools/import_d2r_assassin_auras.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "auras" / "assassin"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-assassin-auras.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# The effect is authored around the character's feet. These are the same cell
# and origin used by the paladin aura importer so the characters share scale.
SOURCE_CELL = 160
SOURCE_ORIGIN = (80, 100)
OUTPUT_CELL = 128
DRAW_SCALE = SOURCE_CELL / OUTPUT_CELL

# aura name, output slug, frame rate, overlay DCC stems in draw order.
AURAS = (
    ("Blade Sentinel", "blade-sentinel", 16, ("blade_shield",)),
)

# Blade Shield is an expansion overlay; keep the base path as a fallback for
# extractions that flatten the global overlay directories.
OVERLAY_DIRS = ("global/overlays/expansion", "global/overlays")


def overlay_path(source: Path, stem: str) -> Path:
    for relative in OVERLAY_DIRS:
        path = source / relative / f"{stem}.dcc"
        if path.exists():
            return path
    searched = ", ".join(str(source / relative) for relative in OVERLAY_DIRS)
    raise FileNotFoundError(f"missing aura overlay {stem!r}; searched {searched}")


def build_sheet(
    source: Path,
    palette: list[tuple[int, int, int]],
    layers: tuple[str, ...],
    slug: str,
) -> tuple[Image.Image, int]:
    parsed: list[dict] = []
    for stem in layers:
        animation = dcc.parse(overlay_path(source, stem).read_bytes())
        parsed.append(animation["dirs"][0])

    frame_counts = {len(direction["frames"]) for direction in parsed}
    if len(frame_counts) != 1:
        raise ValueError(f"{slug}: layers have mismatched frame counts: {sorted(frame_counts)}")
    columns = frame_counts.pop()
    sheet = Image.new("RGBA", (columns * OUTPUT_CELL, len(layers) * OUTPUT_CELL), (0, 0, 0, 0))

    for row, direction in enumerate(parsed):
        for index, (frame, bitmap) in enumerate(zip(direction["frames"], direction["bitmaps"])):
            left = SOURCE_ORIGIN[0] + frame["xmin"]
            top = SOURCE_ORIGIN[1] + frame["ymin"]
            if (
                left < 0
                or top < 0
                or left + frame["width"] > SOURCE_CELL
                or top + frame["height"] > SOURCE_CELL
            ):
                raise ValueError(f"{slug}: frame {index} falls outside the {SOURCE_CELL}px source cell")
            tile = Image.new("RGBA", (SOURCE_CELL, SOURCE_CELL), (0, 0, 0, 0))
            tile.alpha_composite(
                dcc.frame_image(bitmap, frame["width"], frame["height"], palette),
                (left, top),
            )
            tile = tile.resize((OUTPUT_CELL, OUTPUT_CELL), Image.Resampling.LANCZOS)
            sheet.alpha_composite(tile, (index * OUTPUT_CELL, row * OUTPUT_CELL))

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT_DIR / f"{slug}.png", optimize=True)
    return sheet, columns


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_assassin_auras.py. Do not edit by hand. */",
        "",
        "export interface AssassinAuraArt {",
        "  path: string;",
        "  columns: number;",
        "  rows: number;",
        "  frameRate: number;",
        "  cell: number;",
        "  originX: number;",
        "  originY: number;",
        "  scale: number;",
        "  backRow: number | null;",
        "  frontRow: number | null;",
        "}",
        "",
        "export const ASSASSIN_AURA_ART: Record<string, AssassinAuraArt> = {",
    ]
    for record in sorted(records, key=lambda entry: entry["skill"]):
        lines.append(
            "  "
            + json.dumps(record["skill"])
            + ": { path: "
            + json.dumps(record["path"])
            + f", columns: {record['columns']}, rows: {record['rows']}, frameRate: {record['frameRate']}"
            + f", cell: {OUTPUT_CELL}, originX: {round(SOURCE_ORIGIN[0] * OUTPUT_CELL / SOURCE_CELL)}"
            + f", originY: {round(SOURCE_ORIGIN[1] * OUTPUT_CELL / SOURCE_CELL)}, scale: {DRAW_SCALE:.2f}"
            + f", backRow: {record['backRow'] if record['backRow'] is not None else 'null'}"
            + f", frontRow: {record['frontRow'] if record['frontRow'] is not None else 'null'} }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def build(source: Path) -> None:
    palette = dcc.load_palette(source / "global" / "palette" / "units" / "pal.dat")
    records = []
    for skill, slug, frame_rate, layers in AURAS:
        sheet, columns = build_sheet(source, palette, layers, slug)
        records.append({
            "skill": skill,
            "path": f"assets/d2survivors/auras/assassin/{slug}.png",
            "columns": columns,
            "rows": len(layers),
            "frameRate": frame_rate,
            "backRow": None,
            "frontRow": 0,
        })
        print(f"{slug:16} {sheet.width:4}x{sheet.height:<4} {columns:2} frames x {len(layers)} layer(s)")
    write_metadata(records)
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
