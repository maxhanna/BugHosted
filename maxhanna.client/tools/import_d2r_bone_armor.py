"""Build the necromancer Bone Armor sheet from the D2R overlay extraction.

Diablo II draws Bone Armor as two overlays around the character: a back layer
behind the body and a front layer over it. The extraction ships them as
``global/overlays/boneshieldback.dcc`` and ``boneshieldfront.dcc``, 24 frames
each, plus the 12-frame ``boneshieldemerge.dcc`` cast flash this sheet leaves out
so the aura can loop.

Both layers are composited at their unit-space offsets with the character's feet
at (80, 100) on a 160px cell, then downscaled to 128px. The runtime scales the
cell back up by 1.25, which keeps the original on-screen size and the two 24px
rows under the 4096px texture limit.

``units/pal.dat`` stores BGR triples, so the palette is converted before the
frames are painted.

Usage:
    python tools/import_d2r_bone_armor.py
    python tools/import_d2r_bone_armor.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "auras" / "necromancer" / "bone-armor.png"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-bone-armor.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# Both overlays sit above the feet (y -63..+16), so the cell reserves a little
# headroom. Keeping the same 160 -> 128 downscale as the paladin auras makes the
# runtime's 1.25 draw scale restore the source size.
SOURCE_CELL = 160
SOURCE_ORIGIN = (80, 100)
OUTPUT_CELL = 128
DRAW_SCALE = SOURCE_CELL / OUTPUT_CELL
FRAME_RATE = 16
# Bump when the generated sheet changes so caches fetch the corrected art.
ASSET_VERSION = 1

# layer rows in draw order: back first, then front.
LAYERS = ("boneshieldback", "boneshieldfront")


def build_sheet(source: Path, palette: list[tuple[int, int, int]]) -> tuple[Image.Image, int]:
    parsed = []
    for stem in LAYERS:
        path = source / "global" / "overlays" / f"{stem}.dcc"
        if not path.exists():
            raise FileNotFoundError(f"missing bone armor overlay: {path}")
        direction = dcc.parse(path.read_bytes())["dirs"][0]
        parsed.append(direction)

    frame_counts = {len(direction["frames"]) for direction in parsed}
    if len(frame_counts) != 1:
        raise ValueError(f"bone armor layers have mismatched frame counts: {sorted(frame_counts)}")
    columns = frame_counts.pop()
    sheet = Image.new("RGBA", (columns * OUTPUT_CELL, len(LAYERS) * OUTPUT_CELL), (0, 0, 0, 0))

    for row, direction in enumerate(parsed):
        for index, (frame, bitmap) in enumerate(zip(direction["frames"], direction["bitmaps"])):
            left = SOURCE_ORIGIN[0] + frame["xmin"]
            top = SOURCE_ORIGIN[1] + frame["ymin"]
            if left < 0 or top < 0 or left + frame["width"] > SOURCE_CELL or top + frame["height"] > SOURCE_CELL:
                raise ValueError(f"{LAYERS[row]}: frame {index} falls outside the {SOURCE_CELL}px source cell")
            tile = Image.new("RGBA", (SOURCE_CELL, SOURCE_CELL), (0, 0, 0, 0))
            tile.alpha_composite(
                dcc.frame_image(bitmap, frame["width"], frame["height"], palette),
                (left, top),
            )
            tile = tile.resize((OUTPUT_CELL, OUTPUT_CELL), Image.Resampling.LANCZOS)
            sheet.alpha_composite(tile, (index * OUTPUT_CELL, row * OUTPUT_CELL))

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT_PATH, optimize=True)
    return sheet, columns


def write_metadata(columns: int) -> None:
    lines = [
        "/* Generated by tools/import_d2r_bone_armor.py. Do not edit by hand. */",
        "",
        "export interface BoneArmorArt {",
        "  path: string;",
        "  columns: number;",
        "  rows: number;",
        "  frameRate: number;",
        "  cell: number;",
        "  originX: number;",
        "  originY: number;",
        "  scale: number;",
        "  backRow: number;",
        "  frontRow: number;",
        "}",
        "",
        "// The two overlays are laid out as one row each: back on top, front below.",
        "export const BONE_ARMOR_ART: BoneArmorArt = {",
        f'  path: "assets/d2survivors/auras/necromancer/bone-armor.png?v={ASSET_VERSION}",',
        f"  columns: {columns},",
        f"  rows: {len(LAYERS)},",
        f"  frameRate: {FRAME_RATE},",
        f"  cell: {OUTPUT_CELL},",
        f"  originX: {round(SOURCE_ORIGIN[0] * OUTPUT_CELL / SOURCE_CELL)},",
        f"  originY: {round(SOURCE_ORIGIN[1] * OUTPUT_CELL / SOURCE_CELL)},",
        f"  scale: {DRAW_SCALE:.2f},",
        f"  backRow: {LAYERS.index('boneshieldback')},",
        f"  frontRow: {LAYERS.index('boneshieldfront')},",
        "};",
        "",
    ]
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def build(source: Path) -> None:
    # `pal.dat` stores BGR; reading it as RGB would swap red and blue.
    palette = [(red, green, blue) for blue, green, red in
               dcc.load_palette(source / "global" / "palette" / "units" / "pal.dat")]
    sheet, columns = build_sheet(source, palette)
    write_metadata(columns)
    print(f"bone-armor      {sheet.width:4}x{sheet.height:<4} {columns:2} frames x {len(LAYERS)} layer(s)")
    print(f"wrote {OUTPUT_PATH.relative_to(PROJECT_ROOT)}")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
