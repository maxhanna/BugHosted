"""Bake the original Diablo II Bone Wall neutral sprite into a strip.

The necromancer's Bone Wall is a monster unit rather than a missile. Its
original art lives at ``global/monsters/bw/tr/bwtrlitnuhth.dcc`` (the lit
neutral idle), with four directions and one frame each. D2 builds the barrier
from repeated Bone Wall units, so the arena reuses this neutral cluster as the
tile for its wall instead of drawing a line of generic bones.

The four direction boxes are bottom-aligned on one shared transparent cell.
That keeps the piles on a consistent ground line when the runtime repeats them
along a wall. ``units/pal.dat`` stores BGR triples, so the palette is converted
before the frames are painted.

Usage:
    python tools/import_d2r_bone_wall.py
    python tools/import_d2r_bone_wall.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "effects" / "bone-wall.png"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-bone-wall.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

SOURCE_DCC = ("global", "monsters", "bw", "tr", "bwtrlitnuhth.dcc")
PALETTE_PATH = ("global", "palette", "units", "pal.dat")
# Bump when the generated strip changes so the browser does not keep a stale copy.
ASSET_VERSION = 1


def build_sheet(source: Path) -> tuple[Image.Image, int, int, int]:
    path = source.joinpath(*SOURCE_DCC)
    animation = dcc.parse(path.read_bytes())
    if len(animation["dirs"]) != 4:
        raise RuntimeError(f"expected four Bone Wall directions, found {len(animation['dirs'])}")

    palette = [(red, green, blue) for blue, green, red in
               dcc.load_palette(source.joinpath(*PALETTE_PATH))]
    frames: list[Image.Image] = []
    cell_width = 0
    cell_height = 0
    for direction in animation["dirs"]:
        xmin, ymin, width, height = direction["box"]
        frame = direction["frames"][0]
        canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        canvas.alpha_composite(
            dcc.frame_image(direction["bitmaps"][0], frame["width"], frame["height"], palette),
            (frame["xmin"] - xmin, frame["ymin"] - ymin),
        )
        frames.append(canvas)
        cell_width = max(cell_width, width)
        cell_height = max(cell_height, height)

    sheet = Image.new("RGBA", (cell_width * len(frames), cell_height), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        x = (cell_width - frame.width) // 2
        y = cell_height - frame.height
        sheet.alpha_composite(frame, (index * cell_width + x, y))
    return sheet, len(frames), cell_width, cell_height


def write_metadata(directions: int, cell_width: int, cell_height: int) -> None:
    lines = [
        "/* Generated by tools/import_d2r_bone_wall.py. Do not edit by hand. */",
        "",
        "export interface BoneWallArt {",
        "  path: string;",
        "  directions: number;",
        "  cellWidth: number;",
        "  cellHeight: number;",
        "}",
        "",
        "export const BONE_WALL_ART: BoneWallArt = {",
        f'  path: "assets/d2survivors/effects/bone-wall.png?v={ASSET_VERSION}",',
        f"  directions: {directions},",
        f"  cellWidth: {cell_width},",
        f"  cellHeight: {cell_height},",
        "};",
        "",
    ]
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)

    sheet, directions, cell_width, cell_height = build_sheet(args.source)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUTPUT, "PNG", optimize=True)
    write_metadata(directions, cell_width, cell_height)
    print(f"bone-wall  {sheet.width}x{sheet.height}  {directions} directions  {cell_width}x{cell_height} cells")
    print(f"wrote {OUTPUT.relative_to(PROJECT_ROOT)}")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))