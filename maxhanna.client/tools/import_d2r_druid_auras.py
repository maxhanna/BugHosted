"""Build the Oak Sage and Heart of Wolverine foot overlays from the D2R extraction.

The Diablo II overlay table points both druid spirits at one-direction legacy
DCCs under ``data/global/overlays/expansion``:

    oak_sage            -> oak_sage_Aura.dcc       11 frames, AnimRate 6
    heart_of_wolverine  -> Heart_of_Wolverine.dcc  30 frames, AnimRate 16

Both use ``Trans: 3`` (black alpha), so their baked black keyline is converted
to alpha instead of being drawn as a hard outline. The source palette is stored
as BGR; swapping it restores the original orange leaf-glow and red wolverine
tones instead of the blue cast produced by the older RGB aura importer.

The output keeps the native overlay resolution in a 128x80 cell. The runtime
draws each cell with the unit origin at (64, 40), which is the spirit's ground
point.

Usage:
    python tools/import_d2r_druid_auras.py
    python tools/import_d2r_druid_auras.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "auras" / "druid"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-druid-auras.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# The widest frame is Heart of Wolverine at 122x66; the tallest is 66. A little
# room around the origin keeps every frame inside the cell without rescaling.
CELL_WIDTH = 128
CELL_HEIGHT = 80
ORIGIN_X = 64
ORIGIN_Y = 40
DRAW_SCALE = 1.0

# Trans 3 makes black transparent. Darken the source alpha smoothly instead of
# leaving the old black keyline as an opaque halo; the bright body stays solid.
BLACK_FLOOR = 8
ALPHA_GAIN = 1.55

# skill, output slug, DCC stem, overlay table animation rate.
AURAS = (
    ("Oak Sage", "oak-sage-aura", "oak_sage_aura", 11, 6),
    ("Heart of Wolverine", "heart-of-wolverine-aura", "heart_of_wolverine", 30, 16),
)


def load_bgr_palette(path: Path) -> list[tuple[int, int, int]]:
    """Read the D2 units palette, whose bytes are stored blue-green-red."""
    return [(blue, green, red) for red, green, blue in dcc.load_palette(path)]


def apply_black_alpha(image: Image.Image) -> Image.Image:
    """Turn the baked black keyline into soft alpha, as overlay Trans 3 does."""
    pixels = image.load()
    for y in range(image.height):
        for x in range(image.width):
            red, green, blue, alpha = pixels[x, y]
            if alpha == 0:
                continue
            high = max(red, green, blue)
            if high <= BLACK_FLOOR:
                pixels[x, y] = (0, 0, 0, 0)
                continue
            pixels[x, y] = (red, green, blue, min(alpha, min(255, round(high * ALPHA_GAIN))))
    return image


def build_sheet(source: Path, palette: list[tuple[int, int, int]], stem: str, columns: int) -> Image.Image:
    path = source / "global" / "overlays" / "expansion" / f"{stem}.dcc"
    if not path.is_file():
        raise FileNotFoundError(f"missing druid aura overlay: {path}")
    animation = dcc.parse(path.read_bytes())
    if animation["directions"] != 1:
        raise ValueError(f"{stem}: expected one direction, found {animation['directions']}")
    direction = animation["dirs"][0]
    if len(direction["frames"]) != columns:
        raise ValueError(f"{stem}: expected {columns} frames, found {len(direction['frames'])}")

    sheet = Image.new("RGBA", (columns * CELL_WIDTH, CELL_HEIGHT), (0, 0, 0, 0))
    for index, (frame, bitmap) in enumerate(zip(direction["frames"], direction["bitmaps"])):
        image = apply_black_alpha(dcc.frame_image(bitmap, frame["width"], frame["height"], palette))
        left = ORIGIN_X + frame["xmin"]
        top = ORIGIN_Y + frame["ymin"]
        if left < 0 or top < 0 or left + frame["width"] > CELL_WIDTH or top + frame["height"] > CELL_HEIGHT:
            raise ValueError(f"{stem}: frame {index} falls outside the {CELL_WIDTH}x{CELL_HEIGHT} cell")
        sheet.alpha_composite(image, (index * CELL_WIDTH + left, top))
    return sheet


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_druid_auras.py. Do not edit by hand. */",
        "",
        "export interface DruidSpiritAuraArt {",
        "  path: string;",
        "  columns: number;",
        "  rows: number;",
        "  frameRate: number;",
        "  cellWidth: number;",
        "  cellHeight: number;",
        "  originX: number;",
        "  originY: number;",
        "  scale: number;",
        "  alpha: number;",
        "}",
        "",
        "export const DRUID_SPIRIT_AURA_ART: Record<string, DruidSpiritAuraArt> = {",
    ]
    for record in sorted(records, key=lambda entry: entry["skill"]):
        lines.append(
            "  "
            + json.dumps(record["skill"])
            + ": { path: "
            + json.dumps(record["path"])
            + f", columns: {record['columns']}, rows: 1, frameRate: {record['frameRate']}"
            + f", cellWidth: {CELL_WIDTH}, cellHeight: {CELL_HEIGHT}"
            + f", originX: {ORIGIN_X}, originY: {ORIGIN_Y}, scale: {DRAW_SCALE:.2f}, alpha: 0.90 }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")


def build(source: Path) -> None:
    palette = load_bgr_palette(source / "global" / "palette" / "units" / "pal.dat")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    records = []
    for skill, slug, stem, columns, frame_rate in AURAS:
        sheet = build_sheet(source, palette, stem, columns)
        destination = OUTPUT_DIR / f"{slug}.png"
        sheet.save(destination, optimize=True)
        records.append({
            "skill": skill,
            "path": f"assets/d2survivors/auras/druid/{slug}.png",
            "columns": sheet.width // CELL_WIDTH,
            "frameRate": frame_rate,
        })
        print(f"{skill:20} {sheet.width:4}x{sheet.height:<3} {sheet.width // CELL_WIDTH:2} frames @ {frame_rate} fps")
    write_metadata(records)
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays" / "expansion").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays' / 'expansion'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
