"""Copy the barbarian's warcry shouts out of the D2R extraction.

Diablo II gives every warcry its own recorded shout under
``data/global/sfx/skill/barbarian``. The extract's takes are lossless FLAC, so
each one is re-encoded to the client's small mono Ogg/Opus format (see
``d2r_voice_encode.py``) and listed per skill in ``d2-warcry-voice.ts``; the
runtime picks one at random each time a warcry is used.

Run with:
    python tools/import_d2r_barbarian_voice.py
    python tools/import_d2r_barbarian_voice.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from d2r_voice_encode import ENCODED_SUFFIX, build_take, drop_stale_flacs

PROJECT_ROOT = Path(__file__).resolve().parents[1]
VOICE_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "audio" / "voice" / "barbarian"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-warcry-voice.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# skill -> the recorded shout files that belong to it. The names match the
# extraction one to one, so a wrong entry fails loudly instead of going silent.
VOICES = (
    ("Shout", ("shout1", "shout2", "shout3")),
    ("Howl", ("howl1", "howl2", "howl3")),
    ("Taunt", ("taunt1", "taunt2", "taunt3")),
    ("Battle Cry", ("battlecry1", "battlecry2", "battlecry3")),
    ("Battle Orders", ("order1", "order2", "order3")),
    ("Battle Command", ("command1", "command2", "command3")),
    ("War Cry", ("warcry1", "warcry2", "warcry3")),
    ("Grim Ward", ("grimward3", "grimward4", "grimward5")),
)


def write_metadata(skill_files: list[tuple[str, list[str]]]) -> None:
    entries = []
    for skill, files in skill_files:
        lines = ",\n".join(
            "    { path: %s }" % json.dumps(f"assets/d2survivors/audio/voice/barbarian/{name}{ENCODED_SUFFIX}")
            for name in files
        )
        entries.append("  %s: [\n%s,\n  ]" % (json.dumps(skill), lines))

    body = ",\n".join(entries)
    source = """/**
 * The barbarian's recorded warcry shouts, taken from the shipped Diablo II:
 * Resurrected files under data/global/sfx/skill/barbarian. Each warcry has its
 * own set of takes; the game picks one at random on every use.
 *
 * Generated by tools/import_d2r_barbarian_voice.py.
 */

export interface WarcryVoiceLine {
  /** Path of the voice file, relative to the client root. */
  path: string;
}

export const WARCRY_VOICE_LINES: Record<string, WarcryVoiceLine[]> = {
%s
};

/** One of the skill's recorded shouts, or undefined for a skill without one. */
export function randomWarcryVoiceLine(skill: string, random: () => number = Math.random): WarcryVoiceLine | undefined {
  const lines = WARCRY_VOICE_LINES[skill];
  if (!lines?.length) return undefined;
  const index = Math.min(lines.length - 1, Math.floor(Math.max(0, Math.min(0.999999, random())) * lines.length));
  return lines[index];
}

/** True for every skill that has a recorded warcry shout. */
export function hasWarcryVoice(skill: string): boolean {
  return (WARCRY_VOICE_LINES[skill]?.length ?? 0) > 0;
}
""" % body

    METADATA.write_text(source, encoding="utf-8")


def build(source: Path) -> None:
    voice_source = source / "global" / "sfx" / "skill" / "barbarian"
    if not voice_source.is_dir():
        raise FileNotFoundError(f"missing barbarian skill sounds: {voice_source}")
    VOICE_DIR.mkdir(parents=True, exist_ok=True)
    skill_files: list[tuple[str, list[str]]] = []
    for skill, names in VOICES:
        copied = []
        for name in names:
            origin = voice_source / f"{name}.flac"
            if not origin.exists():
                raise FileNotFoundError(f"missing warcry shout: {origin}")
            build_take(origin, VOICE_DIR / f"{name}{ENCODED_SUFFIX}")
            copied.append(name)
        skill_files.append((skill, copied))
        print(f"{skill:16} {len(copied)} take(s)")
    removed = drop_stale_flacs(VOICE_DIR)
    if removed:
        print(f"removed {removed} lossless leftover(s)")
    write_metadata(skill_files)
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
