"""Import Diablo II's classic loading screen animation.

`data/global/ui/loading/loadingscreen_eng.dc6` is the cel the game shows
between the menu and the world: the framed gate, the light ramping up behind
it and the LOADING... plaque, ten 256x256 frames in the loading palette.

The run now streams its own art (class model, aura sheets, act tiles) while
this plays, so the strip is exported once and the component slides one frame
at a time over it.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

import d2r_dc6 as dc6

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ASSET_ROOT = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "ui"
GENERATED = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-loading-screen.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

LOADING_CEL = ("global", "ui", "loading", "loadingscreen_eng.dc6")
LOADING_PALETTE = ("global", "palette", "loading", "pal.dat")
ASSET_NAME = "loading-screen.png"
FRAME_RATE = 10


def build_strip(frames: list[Image.Image]) -> Image.Image:
    cell = frames[0].width
    if any(frame.size != (cell, cell) for frame in frames):
        raise ValueError("loading screen cels are not square")
    strip = Image.new("RGBA", (cell * len(frames), cell), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        strip.paste(frame, (index * cell, 0))
    return strip


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args()

    palette = dc6.load_palette(args.source.joinpath(*LOADING_PALETTE))
    animation = dc6.parse(args.source.joinpath(*LOADING_CEL).read_bytes())
    frames = [dc6.frame_image(frame, palette) for frame in animation["frames"]]
    strip = build_strip(frames)

    ASSET_ROOT.mkdir(parents=True, exist_ok=True)
    strip.save(ASSET_ROOT / ASSET_NAME, optimize=True)

    GENERATED.write_text(
        "// Generated by tools/import_d2r_loading_screen.py. Do not edit by hand.\n"
        "// Diablo II's loadingscreen_eng.dc6: the framed gate with the light ramping\n"
        "// up behind it and the LOADING... plaque, as one horizontal cel strip.\n"
        "\n"
        "export const D2_LOADING_SCREEN = {\n"
        f'  path: "assets/d2survivors/ui/{ASSET_NAME}",\n'
        f"  frames: {len(frames)},\n"
        f"  cell: {frames[0].width},\n"
        f"  frameRate: {FRAME_RATE},\n"
        "} as const;\n",
        encoding="utf-8",
    )
    print(f"wrote {len(frames)} frames of {frames[0].width}px to {ASSET_ROOT / ASSET_NAME}")


if __name__ == "__main__":
    main()
