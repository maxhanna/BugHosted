"""Build the Leap control-effect sheets from the D2R overlay extraction.

Barbarian Leap uses two original Diablo II overlays:

* ``global/overlays/stun.dcc`` is the dizzy two-orbit loop drawn over a
  stunned monster.
* ``global/overlays/bajumplandpuff01.dcc`` is the dust ring kicked up where
  the barbarian lands.

Both DCCs are single-direction animations whose cels are positioned in unit
space around the character's feet. The importer keeps every cel in one shared,
tight crop so the orbit and the dust ring animate in place. The generated
metadata records where the feet sit inside that crop, which lets the runtime
anchor the landing puff exactly on the ground.

Usage:
    python tools/import_d2r_leap_effects.py
    python tools/import_d2r_leap_effects.py --source "C:/path/to/d2r extract/data"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

import d2r_dcc as dcc

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = PROJECT_ROOT / "src" / "assets" / "d2survivors" / "effects"
METADATA = PROJECT_ROOT / "src" / "app" / "d2survivors" / "d2-combat-effects.generated.ts"
DEFAULT_SOURCE = Path.home() / "Desktop" / "d2" / "d2r extract" / "data"

# key, source DCC, output slug, playback rate
EFFECTS = (
    ("stun", "global/overlays/stun.dcc", "stun", 16),
    ("leapLand", "global/overlays/bajumplandpuff01.dcc", "leap-land", 18),
)


def load_animation(source: Path, relative: str) -> dict:
    path = source / relative
    if not path.exists():
        raise FileNotFoundError(f"missing overlay {relative!r} below {source}")
    return dcc.parse(path.read_bytes())["dirs"][0]


def build_effect(source: Path, relative: str, slug: str, palette: list[tuple[int, int, int]]) -> dict:
    direction = load_animation(source, relative)
    frames = direction["frames"]
    bitmaps = direction["bitmaps"]
    if not frames:
        raise ValueError(f"{relative}: no frames")

    left = min(frame["xmin"] for frame in frames)
    right = max(frame["xmin"] + frame["width"] for frame in frames)
    top = min(frame["ymin"] for frame in frames)
    bottom = max(frame["ymin"] + frame["height"] for frame in frames)
    cell_width = right - left
    cell_height = bottom - top

    sheet = Image.new("RGBA", (cell_width * len(frames), cell_height), (0, 0, 0, 0))
    for index, (frame, bitmap) in enumerate(zip(frames, bitmaps)):
        cel = dcc.frame_image(bitmap, frame["width"], frame["height"], palette)
        sheet.alpha_composite(cel, (index * cell_width + frame["xmin"] - left, frame["ymin"] - top))

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    output = OUTPUT_DIR / f"{slug}.png"
    sheet.save(output, optimize=True)
    print(f"{slug:10} {sheet.width:4}x{sheet.height:<4} {len(frames):2} frames, cell {cell_width}x{cell_height}")
    return {
        "path": f"assets/d2survivors/effects/{slug}.png",
        "columns": len(frames),
        "frameRate": 0,
        "cellWidth": cell_width,
        "cellHeight": cell_height,
        # The unit-space origin (the character's feet) inside the shared crop.
        "originX": -left,
        "originY": -top,
    }


def write_metadata(records: list[dict]) -> None:
    lines = [
        "/* Generated by tools/import_d2r_leap_effects.py. Do not edit by hand. */",
        "",
        "export interface D2CombatEffectArt {",
        "  path: string;",
        "  columns: number;",
        "  frameRate: number;",
        "  cellWidth: number;",
        "  cellHeight: number;",
        "  /** Pixels from the left of the shared crop to the character's feet. */",
        "  originX: number;",
        "  /** Pixels from the top of the shared crop to the character's feet. */",
        "  originY: number;",
        "}",
        "",
        "export const D2_COMBAT_EFFECT_ART: Record<\"stun\" | \"leapLand\", D2CombatEffectArt> = {",
    ]
    for record in records:
        lines.append(
            f"  {record['key']}: {{ path: {json.dumps(record['path'])}, columns: {record['columns']}, "
            f"frameRate: {record['frameRate']}, cellWidth: {record['cellWidth']}, "
            f"cellHeight: {record['cellHeight']}, originX: {record['originX']}, originY: {record['originY']} }},"
        )
    lines.append("};")
    lines.append("")
    METADATA.parent.mkdir(parents=True, exist_ok=True)
    METADATA.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {METADATA.relative_to(PROJECT_ROOT)}")


def build(source: Path) -> None:
    palette = dcc.load_palette(source / "global" / "palette" / "units" / "pal.dat")
    records = []
    for key, relative, slug, frame_rate in EFFECTS:
        record = build_effect(source, relative, slug, palette)
        record["key"] = key
        record["frameRate"] = frame_rate
        records.append(record)
    write_metadata(records)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args(argv)
    if not (args.source / "global" / "overlays").is_dir():
        print(f"missing overlay extraction: {args.source / 'global' / 'overlays'}")
        return 1
    build(args.source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
