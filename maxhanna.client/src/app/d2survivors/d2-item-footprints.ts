const BASE_ITEM_FOOTPRINTS_BY_KEY: ReadonlyMap<string, D2ItemFootprint> = new Map(
  Object.entries(D2_BASE_ITEM_FOOTPRINTS).map(([name, footprint]) => [name.toLowerCase(), footprint]),
);

/** Resolve a base item name (case-insensitive) to its D2 inventory footprint. */
export function getD2BaseItemFootprint(baseName: string | undefined | null): D2ItemFootprint | undefined {
  const key = baseName?.trim().toLowerCase();
  return key ? BASE_ITEM_FOOTPRINTS_BY_KEY.get(key) : undefined;
}

/**
 * Fallback for legacy or custom items with no known base. Known D2 bases always
 * resolve through the table above; keep this intentionally conservative.
 */
export function getD2EquipmentTypeFootprint(equipmentType: string | undefined): D2ItemFootprint {
  switch (equipmentType) {
    case "body": return { width: 2, height: 3 };
    case "helmet": case "barbarianHelm": case "druidPelt": case "shield":
    case "paladinShield": case "necromancerHead": case "gloves": case "boots":
      return { width: 2, height: 2 };
    case "belt": return { width: 2, height: 1 };
    case "weapon": case "wand": case "claw": case "orb": return { width: 1, height: 3 };
    default: return { width: 1, height: 1 };
  }
}
