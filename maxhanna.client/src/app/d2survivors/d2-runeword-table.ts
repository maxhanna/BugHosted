/**
 * Every runeword, in the shape the game needs: the exact rune sequence, the
 * base categories that accept it, its required level, the property lines the
 * tooltip shows, and the subset of those properties the stat model understands.
 *
 * Rule (D2): a runeword forms only when a base of a listed category has every
 * one of its sockets filled with exactly these runes, in this order, and with
 * nothing else (a gem or jewel anywhere in the item breaks the word).
 *
 * RotW 3.4 splits some words into ladder/offline and non-ladder values. The
 * values here are the ladder & offline ones, which are the fuller set.
 */
export interface DowStatSource {
  stat: string;
  value: number;
}

export interface RunewordDefinition<Stats> {
  name: string;
  runes: readonly string[];
  /** Base categories from the runeword list ("sword", "melee", "shield", ...). */
  bases: readonly string[];
  requiredLevel: number;
  lines: readonly string[];
  stats: Stats;
}

